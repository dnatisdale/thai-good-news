const fs = require("fs");
const path = require("path");

const shouldBump = process.argv.includes("--bump");

const pkgPath = path.join(__dirname, "..", "package.json");
const pkg = JSON.parse(fs.readFileSync(pkgPath, "utf8"));

if (shouldBump) {
  const parts = String(pkg.version || "1.0.0").split(".").map((n) => parseInt(n, 10) || 0);
  while (parts.length < 3) parts.push(0);
  parts[2] += 1;
  pkg.version = parts.join(".");
  fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + "\n", "utf8");
}

const now = new Date();
const year = now.getFullYear();
const month = String(now.getMonth() + 1).padStart(2, "0");
const day = String(now.getDate()).padStart(2, "0");
const hours = String(now.getHours()).padStart(2, "0");
const mins = String(now.getMinutes()).padStart(2, "0");
const buildDisplay = `${year}-${month}-${day} ${hours}:${mins}`;
const buildId = `${pkg.version}-${now.getTime()}`;

const versionData = {
  version: pkg.version,
  buildDate: buildDisplay,
  buildId,
};

// 1. Write public/version.json for live update checks
const publicVersionPath = path.join(__dirname, "..", "public", "version.json");
fs.writeFileSync(publicVersionPath, JSON.stringify(versionData, null, 2) + "\n", "utf8");

// 2. Write src/buildInfo.js so App.jsx and UpdateNotification know the compiled buildId & date
const srcBuildInfoPath = path.join(__dirname, "..", "src", "buildInfo.js");
const srcContent = `// Auto-generated by scripts/generateVersion.js during npm run build
export const BUILD_INFO = ${JSON.stringify(versionData, null, 2)};
`;
fs.writeFileSync(srcBuildInfoPath, srcContent, "utf8");

// 3. Sync APP_SHELL_CACHE version in public/service-worker.js (preserving audio caches)
const swPath = path.join(__dirname, "..", "public", "service-worker.js");
if (fs.existsSync(swPath)) {
  const swContent = fs.readFileSync(swPath, "utf8");
  const updatedSw = swContent.replace(
    /const APP_SHELL_CACHE = "app-shell-cache-[^"]+";/,
    `const APP_SHELL_CACHE = "app-shell-cache-v${pkg.version}";`
  );
  if (updatedSw !== swContent) {
    fs.writeFileSync(swPath, updatedSw, "utf8");
  }
}

console.log(`[generateVersion] Generated build info: v${pkg.version} (${buildDisplay})`);
